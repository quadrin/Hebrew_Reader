/* build-picture-list.mjs — the pictures the course still wants, as a list an
   image model can be handed.

   The scraped pictures are Wikipedia lead images, and 756 of the 1,089 turned
   out not to show their word (see src/duo/vaguePictures.js). A drawn
   illustration can do what a photograph cannot — show "cold", "sit" or
   "behind" — so data/pictures-wanted.json names, by hand, the words worth
   drawing and a scene for each. This script joins that list to the course:
   the Hebrew, the unit the word is taught in, the key the picture index will
   file it under, and the file name to save it as, and writes it all out as
   Markdown in batches sized for a chat window.

   In:  data/pictures-wanted.json      (hand-picked words and scenes)
        public/duo/unit-NNN.json       (the vocabulary, for Hebrew and unit)
        public/duo/images.json         (what already has a usable picture)
   Out: data/PICTURES-WANTED.md

   Run: node scripts/build-picture-list.mjs */

import fs from "node:fs";
import path from "node:path";

import { glossKey, pictureFor } from "../src/duo/images.js";

const ROOT = path.resolve(import.meta.dirname, "..");
const DUO = path.join(ROOT, "public", "duo");
const WANTED = path.join(ROOT, "data", "pictures-wanted.json");
const OUT = path.join(ROOT, "data", "PICTURES-WANTED.md");
const BATCH = 25;

const { style, items } = JSON.parse(fs.readFileSync(WANTED, "utf8"));
const images = JSON.parse(fs.readFileSync(path.join(DUO, "images.json"), "utf8"));

/* the gloss as the list names it: the first sense, grammar tags dropped */
const clean = (en) => String(en).replace(/\([^)]*\)/g, "").split(/[;,/]/)[0].replace(/\s+/g, " ").trim().toLowerCase();
/* the file name the scraper would have used for this key */
const fileFor = (key) => key.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/* every gloss in the course, first unit it appears in */
const course = new Map();
for (let n = 1; n <= 240; n++) {
  const p = path.join(DUO, `unit-${String(n).padStart(3, "0")}.json`);
  if (!fs.existsSync(p)) continue;
  const doc = JSON.parse(fs.readFileSync(p, "utf8"));
  for (const w of doc.words || []) {
    if (!w.he || !w.en) continue;
    const c = clean(w.en);
    if (c && !course.has(c)) course.set(c, { he: w.he, en: w.en, unit: n, word: w });
  }
}

const rows = [];
const problems = [];
const seenKeys = new Set();
for (const [en, prompt] of items) {
  const hit = course.get(en);
  if (!hit) { problems.push(`"${en}" is not a gloss the course teaches`); continue; }
  const key = glossKey(en);
  if (seenKeys.has(key)) { problems.push(`"${en}" files under "${key}", which is already in the list`); continue; }
  seenKeys.add(key);
  if (pictureFor(images, hit.word)) problems.push(`"${en}" already has a usable picture`);
  rows.push({ en, key, file: fileFor(key), he: hit.he, unit: hit.unit, prompt });
}
rows.sort((a, b) => a.unit - b.unit || a.en.localeCompare(b.en));

if (problems.length) {
  console.error(`${problems.length} problems:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

const md = [];
md.push("# Pictures wanted");
md.push("");
md.push(`${rows.length} words from units ${rows[0].unit} to ${rows[rows.length - 1].unit} that have no usable picture and could be drawn. Generated by \`scripts/build-picture-list.mjs\` from \`data/pictures-wanted.json\`; edit the JSON, not this file.`);
md.push("");
md.push("## How to use this");
md.push("");
md.push("1. Paste the **Style** paragraph and one **Batch** into ChatGPT (or any image model) and ask for one square image per line.");
md.push("2. Save each image under the **file** name given, as a 256×256 WebP, into `public/duo/img/`.");
md.push("3. Add an entry to `public/duo/images.json` under the **key** given, for example:");
md.push("");
md.push("   ```json");
md.push('   "cold": { "f": "cold", "gen": true, "by": "generated", "lic": "Generated image", "src": "ChatGPT, from data/pictures-wanted.json" }');
md.push("   ```");
md.push("");
md.push("   `gen: true` matters: many of these keys are on the list of scraped pictures the course hides (`src/duo/vaguePictures.js`), and the flag is what says this one is a drawn replacement to be shown. `lic` and `src` must both be filled in, or `npm run check:duo` will complain. Where a key already has a scraped entry, replace it.");
md.push("4. Run `npm run check:duo`. The lesson builder and the word drill pick the new pictures up on their own.");
md.push("");
md.push("## Style");
md.push("");
md.push(style);
md.push("");
for (let i = 0; i < rows.length; i += BATCH) {
  const batch = rows.slice(i, i + BATCH);
  md.push(`## Batch ${i / BATCH + 1} — units ${batch[0].unit} to ${batch[batch.length - 1].unit}`);
  md.push("");
  md.push("| # | word | Hebrew | unit | key | file | prompt |");
  md.push("|---|---|---|---|---|---|---|");
  batch.forEach((r, j) => {
    md.push(`| ${i + j + 1} | ${r.en} | ${r.he} | ${r.unit} | \`${r.key}\` | \`${r.file}.webp\` | ${r.prompt} |`);
  });
  md.push("");
  md.push("Prompts for this batch, one per line:");
  md.push("");
  batch.forEach((r, j) => md.push(`${i + j + 1}. ${r.file}: ${r.prompt}`));
  md.push("");
}

fs.writeFileSync(OUT, md.join("\n"));
console.log(`wrote ${rows.length} pictures in ${Math.ceil(rows.length / BATCH)} batches to ${path.relative(ROOT, OUT)}`);
